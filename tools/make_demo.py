#!/usr/bin/env python3
"""Builds demo/index.html: the web GUI page of the firmware, with a mock layer instead of a Teensy.

The page is the raw string R"AIOHTML( ... )AIOHTML" in zWebServer.ino. The mock replaces fetch(): reads return empty
(zero) data, every write is ignored. Run it after the web page changed:  python3 tools/make_demo.py
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'AIO_v4_Firmware_WebConfig', 'zWebServer.ino')
OUT = os.path.join(ROOT, 'demo', 'index.html')
VER = re.search(r'#define FW_VERSION "([^"]+)"', open(os.path.join(ROOT, 'AIO_v4_Firmware_WebConfig', 'zConfig.h'), encoding='utf-8').read()).group(1)

MOCK = r'''<script>
// DEMO: no Teensy here. Reads give empty data, writes do nothing. Generated by tools/make_demo.py.
(function () {
  function empty(o) {
    return new Proxy(o || {}, { get: function (t, k) {
      if (k in t) return t[k];
      if (typeof k === 'symbol' || k === 'then' || k === 'toJSON') return undefined;
      return 0;
    } });
  }
  var status = empty({ fwVer: '%VER%', build: 'demo', cfg: empty({ wasSource: 4, tm171On: true, fwVersion: '%VER%' }),
                       keya_was: empty({}), j1939: empty({}), adsAz: empty({}) });   // nested objects the page reads
  window.fetch = function (url) {
    var u = String(url), isStatus = u.indexOf('/api/status') >= 0;
    var write = /save|cmd|calib|zero|note|set|wascal|tm171|gpscmd|keyacfg|pved|\?.*(write|cal|start|stop)=/.test(u) && !isStatus;
    var msg = document.getElementById('sb');
    if (write && msg && u.indexOf('/api/wcstat') < 0 && u.indexOf('read=1') < 0) msg.textContent = 'Demo: nothing is sent, no device connected.';
    return Promise.resolve({
      ok: true, status: 200,
      json: function () { return Promise.resolve(isStatus ? status : u.indexOf('cmd=status') >= 0 ? empty({ ver: '%VER%', last: 'demo', boot: 'demo' }) : empty({})); },
      text: function () { return Promise.resolve(write ? 'OK' : ''); }
    });
  };
})();
</script>'''

BANNER = ('<div style="background:#7c2d12;color:#fed7aa;text-align:center;padding:6px 10px;font:13px sans-serif">'
          'DEMO &mdash; read only, no device connected. Browse the tabs to see the options; nothing is saved or sent. '
          'Firmware %VER%.</div>')

def main():
    s = open(SRC, encoding='utf-8', newline='').read()
    html = s[s.index('R"AIOHTML(') + 10:s.index(')AIOHTML"')].replace('\r\n', '\n')
    html = html.replace('<head>', '<head>\n' + MOCK.replace('%VER%', VER), 1)
    html = html.replace('<body>', '<body>\n' + BANNER.replace('%VER%', VER), 1)
    html = html.replace('<title>AIO v4 Config</title>', '<title>AIO v4 Config (demo)</title>', 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(html)
    print('wrote', OUT, len(html), 'bytes, firmware', VER)

if __name__ == '__main__':
    sys.exit(main())
